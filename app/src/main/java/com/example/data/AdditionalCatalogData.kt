    fun deriveSectionLetter(title: String): String {
        val trimmed = title.trim()
        val first = trimmed.firstOrNull() ?: return "ا"
        return when (first) {
            'أ', 'إ', 'آ', 'ا' -> "ا"
            'ک', 'ك' -> "ک"
            'ی', 'ي', 'ے' -> "ی"
            'ہ', 'ه', 'ھ' -> "ہ"
            else -> first.toString()
        }
    }

